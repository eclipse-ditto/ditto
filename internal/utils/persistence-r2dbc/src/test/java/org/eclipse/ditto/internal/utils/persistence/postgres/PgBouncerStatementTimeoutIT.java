/**
 * Proves how {@code statement_timeout} is enforced behind a PgBouncer in {@code pool_mode = transaction}, for the roles
 * created by the shipped provisioning script {@code deployment/postgres/provisioning/01-roles-and-grants.sql}.
 * <p>
 * The client binds {@code ditto.postgresql.statement-timeout} as a startup parameter. A PgBouncer that lists
 * {@code statement_timeout} in {@code ignore_startup_parameters} drops it, so the value is silently not enforced. A
 * role default ({@code ALTER ROLE ... SET statement_timeout}) is: PostgreSQL applies it to every server session opened
 * as that role. That requires PgBouncer to open its server connections as the connecting client's role, i.e. its
 * {@code [databases]} entry must not force a {@code user=}. The PgBouncer configuration is therefore written out
 * explicitly below rather than generated by the image. Verified with PgBouncer 1.26.0.
 * </p>
 * <p>
 * Every client here uses the production wiring ({@link ConnectionPoolFactory}). Through PgBouncer it always sets a 2s
 * {@code ditto.postgresql.statement-timeout}, so the startup parameter is always sent; only the role default differs.
 * </p>
 * <p>
 * The PgBouncer image is pinned to the version the behaviour was verified with. Only a missing Docker environment
 * skips the class; a PgBouncer or PostgreSQL image that cannot be pulled or started fails it.
 * </p>
 */
public final class PgBouncerStatementTimeoutIT {

    private static final String SUPERUSER = "postgres";
    private static final String SUPERUSER_PASSWORD = "superuser_secret";
    private static final String DATABASE = "ditto";
    private static final String RUNTIME_ROLE = "ditto_app";
    private static final String RUNTIME_PASSWORD = "app_secret";
    private static final String DDL_ROLE = "ditto_ddl";
    private static final String DDL_PASSWORD = "ddl_secret";
    private static final int PGBOUNCER_PORT = 6432;
    /** PgBouncer 1.26.0, the version whose startup-parameter handling the docs describe. */
    private static final String PGBOUNCER_IMAGE = "edoburu/pgbouncer:v1.26.0-p0";

    private static final Path PROVISIONING_SCRIPT =
            Path.of("deployment", "postgres", "provisioning", "01-roles-and-grants.sql");

    /*
     * - The [databases] entry names host, port and dbname only: no user=, so each server connection logs in as the
     *   role of the client it serves and gets that role's defaults.
     * - statement_timeout in ignore_startup_parameters: PgBouncer refuses a startup parameter it neither tracks nor
     *   ignores (08P01 "unsupported startup parameter: statement_timeout"). Ignored, the client's value is dropped,
     *   which is the setup in which only a role default is enforced. (Listed in track_extra_parameters instead,
     *   PgBouncer applies each client's value per transaction; that setup is not what this test covers.)
     * - Plain-text passwords in the auth_file let PgBouncer answer SCRAM on both sides.
     */
    private static final String PGBOUNCER_INI = """
            [databases]
            ditto = host=postgres port=5432 dbname=ditto

            [pgbouncer]
            listen_addr = 0.0.0.0
            listen_port = 6432
            pool_mode = transaction
            default_pool_size = 2
            auth_type = scram-sha-256
            auth_file = /etc/pgbouncer/userlist.txt
            admin_users = postgres
            ignore_startup_parameters = extra_float_digits,statement_timeout
            """;

    private static final String PGBOUNCER_USERLIST = """
            "postgres" "superuser_secret"
            "ditto_ddl" "ddl_secret"
            "ditto_app" "app_secret"
            """;

    /** Client-side statement-timeout of every pool in this test: sent as a startup parameter. */
    private static final Duration CLIENT_STATEMENT_TIMEOUT = Duration.ofSeconds(2);
    /** The short role default used to observe a cancellation quickly. */
    private static final String SHORT_ROLE_TIMEOUT = "2s";
    private static final int SLEEP_SECONDS = 5;
    private static final String LONG_STATEMENT = "DO $$ BEGIN PERFORM pg_sleep(" + SLEEP_SECONDS + "); END $$;";
    private static final String QUERY_CANCELED = "57014";
    private static final String ALWAYS_ALIVE = "always-alive";

    private static Network network;
    private static PostgreSQLContainer<?> postgres;
    private static GenericContainer<?> pgbouncer;
    private static boolean schemaSeeded = false;

    @BeforeClass
    public static void start() throws Exception {
        Assume.assumeTrue("No Docker environment — skipping PgBouncerStatementTimeoutIT",
                DockerClientFactory.instance().isDockerAvailable());

        network = Network.newNetwork();
        postgres = PostgresDbResource.newContainer()
                .withNetwork(network)
                .withNetworkAliases("postgres")
                .withDatabaseName(DATABASE)
                .withUsername(SUPERUSER)
                .withPassword(SUPERUSER_PASSWORD);
        postgres.start();

        pgbouncer = new GenericContainer<>(DockerImageName.parse(PGBOUNCER_IMAGE))
                .withNetwork(network)
                .withNetworkAliases("pgbouncer")
                // an existing pgbouncer.ini stops the image's entrypoint from generating its own.
                .withCopyToContainer(Transferable.of(PGBOUNCER_INI), "/etc/pgbouncer/pgbouncer.ini")
                .withCopyToContainer(Transferable.of(PGBOUNCER_USERLIST), "/etc/pgbouncer/userlist.txt")
                .withExposedPorts(PGBOUNCER_PORT)
                .waitingFor(Wait.forListeningPort());
        pgbouncer.start();

        runProvisioningScript();
    }

    @AfterClass
    public static void stop() {
        if (pgbouncer != null) {
            pgbouncer.stop();
        }
        if (postgres != null) {
            postgres.stop();
        }
        if (network != null) {
            network.close();
        }
    }

    /**
     * The provisioning script's role default reaches transaction-pooled sessions of the runtime role, and the client's
     * own startup value does not; the DDL role deliberately has no default.
     */
    @Test
    public void provisionedRuntimeRoleTimeoutIsInEffectBehindTransactionPooling() {
        assertThat(showStatementTimeout(RUNTIME_ROLE, RUNTIME_PASSWORD))
                .as("statement_timeout of a %s session through transaction-mode PgBouncer", RUNTIME_ROLE)
                .isEqualTo("1min");
        assertThat(showStatementTimeout(DDL_ROLE, DDL_PASSWORD))
                .as("statement_timeout of a %s session through transaction-mode PgBouncer", DDL_ROLE)
                .isEqualTo("0");
    }

    /**
     * With the provisioned role default (shortened to 2s so the test does not wait a minute), a statement that runs
     * longer is cancelled with SQLSTATE 57014 behind transaction-mode PgBouncer.
     */
    @Test
    public void longStatementIsCancelledByRuntimeRoleDefaultBehindTransactionPooling() throws Exception {
        assertThat(runtimeRoleTimeoutDefault())
                .as("statement_timeout default of %s set by the provisioning script", RUNTIME_ROLE)
                .isNotNull();
        withRuntimeRoleTimeout(SHORT_ROLE_TIMEOUT, () -> {
            // the client's own 2s value is dropped by PgBouncer, so a 57014 within the 5s sleep can only come from
            // the role default.
            final Throwable thrown = catchThrowable(PgBouncerStatementTimeoutIT::runLongStatementAsRuntimeRole);

            assertThat(thrown).as("pg_sleep(%s) was cancelled, not run to completion", SLEEP_SECONDS).isNotNull();
            assertThat(sqlStates(thrown))
                    .as("SQLSTATE %s (query_canceled) in the failure cause chain: %s", QUERY_CANCELED, thrown)
                    .contains(QUERY_CANCELED);
        });
    }

    /**
     * Without a role default the same statement runs to completion: the client's 2s startup statement_timeout does not
     * reach the server connection behind transaction-mode PgBouncer.
     */
    @Test
    public void clientStartupTimeoutIsNotEnforcedBehindTransactionPooling() throws Exception {
        withRuntimeRoleTimeout(null, () -> {
            final long start = System.nanoTime();
            runLongStatementAsRuntimeRole();
            final Duration elapsed = Duration.ofNanos(System.nanoTime() - start);

            assertThat(elapsed)
                    .as("pg_sleep(%s) ran to completion despite the client's %s statement-timeout", SLEEP_SECONDS,
                            CLIENT_STATEMENT_TIMEOUT)
                    .isGreaterThanOrEqualTo(Duration.ofSeconds(SLEEP_SECONDS));
        });
    }

    /**
     * On a direct connection the client's startup value overrides the role default, and {@code statement-timeout = 0}
     * sends none, so the role default applies: once the provisioning script ran, 0 no longer means "no timeout".
     */
    @Test
    public void zeroClientTimeoutLeavesTheRoleDefaultInEffectOnADirectConnection() {
        assertThat(showStatementTimeout(directPoolAsRuntimeRole(Duration.ZERO)))
                .as("statement_timeout of a direct %s session with statement-timeout = 0", RUNTIME_ROLE)
                .isEqualTo("1min");
        assertThat(showStatementTimeout(directPoolAsRuntimeRole(CLIENT_STATEMENT_TIMEOUT)))
                .as("statement_timeout of a direct %s session with statement-timeout = %s", RUNTIME_ROLE,
                        CLIENT_STATEMENT_TIMEOUT)
                .isEqualTo("2s");
    }

    /**
     * The persistence pings consume their pid streams throttled, far more slowly than one statement may run under the
     * role default. Read in short statements (windows in both orders), the streams survive a consumer that pauses for
     * longer than the role default (2s here) after the first window, behind transaction-mode PgBouncer, as the runtime
     * role: every pid is delivered and no statement is cancelled (the streams run without retries, so a cancellation
     * would fail them).
     */
    @Test
    public void pausedPingStreamsAreNotCancelledByTheRuntimeRoleDefaultBehindTransactionPooling() throws Exception {
        final int pids = 1_000;
        final int batchSize = 100;
        seedAlwaysAlivePolicies(pids);
        final ActorSystem system = ActorSystem.create("PgBouncerStatementTimeoutIT");
        try {
            withRuntimeRoleTimeout(SHORT_ROLE_TIMEOUT, () -> {
                final DittoPostgresClient client = DittoPostgresClient.forConnectionPool(
                        poolThroughPgBouncer(RUNTIME_ROLE, RUNTIME_PASSWORD),
                        DefaultPostgresConfig.of(ConfigFactory.empty()));
                try {
                    final PostgresReadJournal readJournal =
                            PostgresReadJournal.of(PostgresPersistenceOperations.of(client, "policies"));
                    final Materializer mat = SystemMaterializer.get(system).materializer();
                    final Map<String, Source<String, NotUsed>> streams = new LinkedHashMap<>();
                    streams.put("ID order",
                            readJournal.getJournalPidsWithTag(ALWAYS_ALIVE, batchSize, Duration.ZERO, mat, false));
                    streams.put("ID order, newest event",
                            readJournal.getJournalPidsWithTag(ALWAYS_ALIVE, batchSize, Duration.ZERO, mat, true));
                    streams.put("priority order",
                            readJournal.getJournalPidsWithTagOrderedByPriorityTag(ALWAYS_ALIVE, Duration.ZERO));
                    for (final Map.Entry<String, Source<String, NotUsed>> stream : streams.entrySet()) {
                        assertThat(pauseAfterFirstPageThenDrain(stream.getValue(), batchSize, mat))
                                .as("%s: every pid, once", stream.getKey())
                                .hasSize(pids)
                                .doesNotHaveDuplicates();
                    }
                } finally {
                    client.close();
                }
            });
        } finally {
            TestKit.shutdownActorSystem(system);
        }
    }

    private static List<String> pauseAfterFirstPageThenDrain(final Source<String, NotUsed> stream,
            final int batchSize, final Materializer mat) throws Exception {
        final List<String> received = new ArrayList<>();
        // longer than the 2s role default, as a throttled ping waits between two statements.
        PidStreamTestSupport.pullPauseDrain(stream, batchSize, Duration.ofSeconds(SLEEP_SECONDS), () -> { },
                received, mat, Duration.ofSeconds(30));
        return received;
    }

    /** Creates the persistence schema as the DDL role and seeds always-alive policies, once. */
    private static void seedAlwaysAlivePolicies(final int pids) {
        if (schemaSeeded) {
            return;
        }
        final ConnectionFactory ddl = ConnectionFactories.get(ConnectionFactoryOptions.builder()
                .option(ConnectionFactoryOptions.DRIVER, "postgresql")
                .option(ConnectionFactoryOptions.HOST, postgres.getHost())
                .option(ConnectionFactoryOptions.PORT, postgres.getMappedPort(PostgreSQLContainer.POSTGRESQL_PORT))
                .option(ConnectionFactoryOptions.DATABASE, DATABASE)
                .option(ConnectionFactoryOptions.USER, DDL_ROLE)
                .option(ConnectionFactoryOptions.PASSWORD, DDL_PASSWORD)
                .build());
        PostgresSchemaManager.of(ddl, PostgresSchema.descriptor()).bootstrap();
        Mono.usingWhen(Mono.from(ddl.create()),
                        connection -> Flux.from(connection.createStatement("INSERT INTO policies_journal "
                                                + "(pid, sn, manifest, tags, event) SELECT 'policy:pgb-ping:' || "
                                                + "lpad(i::text, 6, '0'), 1, 'manifest', ARRAY['" + ALWAYS_ALIVE
                                                + "', 'priority-' || (i % 10)], '{}'::jsonb "
                                                + "FROM generate_series(1, " + pids + ") AS i")
                                        .execute())
                                .flatMap(Result::getRowsUpdated)
                                .then(),
                        Connection::close)
                .block(Duration.ofSeconds(30));
        schemaSeeded = true;
    }

    private static String showStatementTimeout(final String role, final String password) {
        return showStatementTimeout(poolThroughPgBouncer(role, password));
    }

    private static String showStatementTimeout(final ConnectionPool pool) {
        try {
            return Mono.usingWhen(pool.create(),
                            connection -> Mono.from(connection.createStatement("SHOW statement_timeout").execute())
                                    .flatMap(result -> Mono.from(result.map((row, meta) -> row.get(0, String.class)))),
                            Connection::close)
                    .block(Duration.ofSeconds(20));
        } finally {
            pool.disposeLater().block(Duration.ofSeconds(20));
        }
    }

    private static void runLongStatementAsRuntimeRole() {
        final ConnectionPool pool = poolThroughPgBouncer(RUNTIME_ROLE, RUNTIME_PASSWORD);
        try {
            Mono.usingWhen(pool.create(),
                            connection -> Flux.from(connection.createStatement(LONG_STATEMENT).execute())
                                    .flatMap(Result::getRowsUpdated)
                                    .then(),
                            Connection::close)
                    .block(Duration.ofSeconds(30));
        } finally {
            pool.disposeLater().block(Duration.ofSeconds(20));
        }
    }

    /** A pool built by the production {@link ConnectionPoolFactory}, through PgBouncer, as the given role. */
    private static ConnectionPool poolThroughPgBouncer(final String role, final String password) {
        return pool(pgbouncer.getHost(), pgbouncer.getMappedPort(PGBOUNCER_PORT), "transaction", role, password,
                CLIENT_STATEMENT_TIMEOUT);
    }

    /** A pool built by the production {@link ConnectionPoolFactory}, directly to PostgreSQL, as the runtime role. */
    private static ConnectionPool directPoolAsRuntimeRole(final Duration clientStatementTimeout) {
        return pool(postgres.getHost(), postgres.getMappedPort(PostgreSQLContainer.POSTGRESQL_PORT), "direct",
                RUNTIME_ROLE, RUNTIME_PASSWORD, clientStatementTimeout);
    }

    private static ConnectionPool pool(final String host, final int port, final String poolerMode, final String role,
            final String password, final Duration clientStatementTimeout) {
        final String uri = "r2dbc:postgresql://" + host + ":" + port + "/" + DATABASE;
        return ConnectionPoolFactory.createConnectionPool(DefaultPostgresConfig.of(ConfigFactory.parseString(
                "postgresql {\n"
                        + "  uri = \"" + uri + "\"\n"
                        + "  username = \"" + role + "\"\n"
                        + "  password = \"" + password + "\"\n"
                        + "  pooler-mode = \"" + poolerMode + "\"\n"
                        + "  statement-timeout = " + clientStatementTimeout.toMillis() + "ms\n"
                        + "  ssl.mode = \"disable\"\n"
                        + "  pool.max-size = 2\n"
                        + "}\n")));
    }

    /**
     * Runs {@code body} with the runtime role's {@code statement_timeout} default set to {@code value} ({@code null}:
     * none), then restores the previous default. Role defaults apply when a server session starts, so PgBouncer's
     * server connections are recycled after each change.
     */
    private static void withRuntimeRoleTimeout(@Nullable final String value, final ThrowingRunnable body)
            throws Exception {
        final String previous = runtimeRoleTimeoutDefault();
        setRuntimeRoleTimeoutDefault(value);
        try {
            body.run();
        } finally {
            setRuntimeRoleTimeoutDefault(previous);
        }
    }

    @Nullable
    private static String runtimeRoleTimeoutDefault() throws Exception {
        final String value = psqlAsSuperuser("SELECT option_value FROM pg_db_role_setting s, "
                + "pg_options_to_table(s.setconfig) WHERE s.setrole = '" + RUNTIME_ROLE + "'::regrole "
                + "AND s.setdatabase = 0 AND option_name = 'statement_timeout'").strip();
        return value.isEmpty() ? null : value;
    }

    private static void setRuntimeRoleTimeoutDefault(@Nullable final String value) throws Exception {
        psqlAsSuperuser(value == null
                ? "ALTER ROLE " + RUNTIME_ROLE + " RESET statement_timeout"
                : "ALTER ROLE " + RUNTIME_ROLE + " SET statement_timeout = '" + value + "'");
        // close PgBouncer's existing server connections; new ones start with the changed role default.
        final Container.ExecResult reconnect = postgres.execInContainer("env", "PGPASSWORD=" + SUPERUSER_PASSWORD,
                "psql", "-X", "-v", "ON_ERROR_STOP=1", "-h", "pgbouncer", "-p", String.valueOf(PGBOUNCER_PORT),
                "-U", SUPERUSER, "-d", "pgbouncer", "-c", "RECONNECT " + DATABASE);
        assertThat(reconnect.getExitCode()).as("PgBouncer RECONNECT failed: %s", reconnect.getStderr()).isZero();
    }

    private static String psqlAsSuperuser(final String sql) throws Exception {
        final Container.ExecResult result = postgres.execInContainer("psql", "-X", "-q", "-t", "-A",
                "-v", "ON_ERROR_STOP=1", "-U", SUPERUSER, "-d", DATABASE, "-c", sql);
        assertThat(result.getExitCode()).as("psql failed for <%s>: %s", sql, result.getStderr()).isZero();
        return result.getStdout();
    }

    /** Runs the shipped provisioning script as the superuser, exactly as the ops runbook does. */
    private static void runProvisioningScript() throws Exception {
        postgres.copyFileToContainer(MountableFile.forHostPath(locateProvisioningScript()),
                "/tmp/01-roles-and-grants.sql");
        final Container.ExecResult result = postgres.execInContainer("psql", "-X", "-v", "ON_ERROR_STOP=1",
                "-U", SUPERUSER, "-d", DATABASE, "-v", "ddl_pw=" + DDL_PASSWORD, "-v", "app_pw=" + RUNTIME_PASSWORD,
                "-f", "/tmp/01-roles-and-grants.sql");
        assertThat(result.getExitCode()).as("provisioning script failed: %s", result.getStderr()).isZero();
    }

    /** Finds the provisioning script from the module directory (or any directory below the repository root). */
    private static Path locateProvisioningScript() {
        for (Path dir = Path.of("").toAbsolutePath(); dir != null; dir = dir.getParent()) {
            final Path candidate = dir.resolve(PROVISIONING_SCRIPT);
            if (Files.isRegularFile(candidate)) {
                return candidate;
            }
        }
        throw new IllegalStateException("Provisioning script " + PROVISIONING_SCRIPT + " not found above "
                + Path.of("").toAbsolutePath());
    }

    private static Set<String> sqlStates(@Nullable final Throwable thrown) {
        final Set<String> sqlStates = new HashSet<>();
        for (Throwable t = thrown; t != null && t != t.getCause(); t = t.getCause()) {
            if (t instanceof R2dbcException r2dbc && r2dbc.getSqlState() != null) {
                sqlStates.add(r2dbc.getSqlState());
            }
        }
        return sqlStates;
    }

    @FunctionalInterface
    private interface ThrowingRunnable {

        void run() throws Exception;
    }

}
